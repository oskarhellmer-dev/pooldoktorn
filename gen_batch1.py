#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Genererar bilder för batch 1 (vattenvårdsguider) – 16:9 webp 1200/800/400 + jpg."""
import os, sys, json, urllib.request
from io import BytesIO
from PIL import Image

OUT = "/home/clawd/pooldoktorn-astro/public/bilder"
os.makedirs(OUT, exist_ok=True)
STYLE = ("professional photography, photorealistic, shot on 35mm, soft natural daylight, "
         "clean editorial style, high detail, no text, no watermark, no people")
NORDIC = "Swedish/Nordic garden setting, muted natural palette"

JOBS = {
 "cyanursyra-pool": "A swimming pool water test kit with cyanuric acid test strips on the pool edge, clear blue water behind",
 "backspolning-pool": "A pool sand filter with a multi-port valve set to backwash, wastewater flowing out, clean pool in background",
 "mjolkigt-vatten-pool": "A residential swimming pool with cloudy milky white-blue water, surface close-up, garden setting",
 "veckoklor": "A slow-dissolving weekly chlorine tablet held above a swimming pool, pool chemical package blurred behind",
 "snabbklor": "White chlorine granules dissolving in a plastic bucket of water beside a swimming pool, safety gloves nearby",
 "alger-efter-vintern": "A swimming pool covered with green algae and leaves after winter, pool being opened in spring, garden setting",
}

def fal(prompt, key):
    body = json.dumps({"prompt": prompt + ", " + STYLE + ", " + NORDIC,
                       "image_size": "landscape_16_9", "num_images": 1}).encode()
    req = urllib.request.Request("https://fal.run/fal-ai/flux-pro/v1.1", data=body,
        headers={"Authorization": f"Key {key}", "Content-Type": "application/json"})
    return json.load(urllib.request.urlopen(req, timeout=180))["images"][0]["url"]

def save(name, raw):
    im = Image.open(BytesIO(raw)).convert("RGB")
    w, h = im.size; t = 16/9
    if w/h > t:
        nw = int(h*t); x = (w-nw)//2; im = im.crop((x, 0, x+nw, h))
    else:
        nh = int(w/t); y = (h-nh)//2; im = im.crop((0, y, w, y+nh))
    im = im.resize((1200, 675), Image.LANCZOS)
    for tw in (1200, 800, 400):
        im.resize((tw, int(675*tw/1200)), Image.LANCZOS).save(f"{OUT}/{name}-{tw}.webp", "WEBP", quality=82, method=6)
    im.resize((800, 450), Image.LANCZOS).save(f"{OUT}/{name}.jpg", "JPEG", quality=84, optimize=True, progressive=True)

if __name__ == "__main__":
    key = os.environ["FAL_KEY"]
    only = sys.argv[1:] if len(sys.argv) > 1 else list(JOBS)
    for name in only:
        try:
            url = fal(JOBS[name], key)
            raw = urllib.request.urlopen(url, timeout=120).read()
            save(name, raw)
            print("OK", name)
        except Exception as e:
            print("FAIL", name, str(e)[:160])
